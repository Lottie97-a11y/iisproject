"""Write static/samples.js from the images in samples/.

    python tools/embed_samples.py

Run this after adding or changing an image in samples/. Each image is embedded as a
data URL, so the page works when index.html is opened straight from disk (file://) as
well as on GitHub Pages. Embedding also keeps the canvas readable: Chrome blocks
reading pixels from images loaded from file:// paths, and later steps need pixels.
"""
import base64
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SAMPLES = os.path.join(HERE, "..", "samples")
OUT = os.path.join(HERE, "..", "static", "samples.js")
TYPES = {".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg"}


def main():
    entries = []
    for name in sorted(os.listdir(SAMPLES)):
        ext = os.path.splitext(name)[1].lower()
        if ext not in TYPES:
            continue
        with open(os.path.join(SAMPLES, name), "rb") as f:
            data = base64.b64encode(f.read()).decode("ascii")
        entries.append({"name": name, "src": "data:%s;base64,%s" % (TYPES[ext], data)})
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/embed_samples.py from samples/. Do not edit by hand.\n")
        f.write("window.SAMPLES = %s;\n" % json.dumps(entries, indent=1))
    print("wrote %s (%d image(s))" % (os.path.normpath(OUT), len(entries)))


if __name__ == "__main__":
    main()
