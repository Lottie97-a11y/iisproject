"""Write static/recorded_runs.js from the folders in recorded_runs/.

    python tools/embed_runs.py

Run this after tools/make_mocks.py, or after editing a card.json or an image by hand.
Images are embedded as data URLs (like static/samples.js) so the page works when
opened from disk and the canvas can still read their pixels.
"""
import base64
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RUNS = os.path.join(HERE, "..", "recorded_runs")
OUT = os.path.join(HERE, "..", "static", "recorded_runs.js")


def data_url(path):
    with open(path, "rb") as f:
        return "data:image/png;base64," + base64.b64encode(f.read()).decode("ascii")


def main():
    runs = []
    for name in sorted(os.listdir(RUNS)):
        folder = os.path.join(RUNS, name)
        if not os.path.isdir(folder):
            continue
        with open(os.path.join(folder, "card.json"), encoding="utf-8") as f:
            card = json.load(f)
        runs.append({
            "id": name,
            "sample": card.get("sample", "room.png"),  # which image in samples/ this run edits
            "card": card,
            "mask": data_url(os.path.join(folder, "mask.png")),
            "result": data_url(os.path.join(folder, "result.png")),
        })
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/embed_runs.py from recorded_runs/. Do not edit by hand.\n")
        f.write("// Simulated model outputs: drawn in code by tools/make_mocks.py, no model called.\n")
        f.write("window.RECORDED_RUNS = %s;\n" % json.dumps(runs, indent=1))
    print("wrote %s (%d run(s))" % (os.path.normpath(OUT), len(runs)))


if __name__ == "__main__":
    main()
